function _on_ready(self)
    local mat = scene.entity("mat_ground")
    scene.replace(mat, "Material", { baseColor = {0.35, 0.35, 0.38}, metallic = 0, roughness = 0.95 })
    local g = scene.entity()
    scene.replace(g, "Geometry", mesh.box({ 20, 1, 20 }))
    local ground = scene.entity("ground")
    scene.replace(ground, "Transform", { pos = { 0, -1, 0 } })
    scene.replace(ground, "Renderable", { geom = g })
    scene.replace(ground, "MaterialRef", { material = mat })
    local ch = scene.entity("char")
    scene.replace(ch, "Transform", { pos = { 0, 0, 0 } })
-- entity-form gltf load: skinned model (the table API supports skinning too; kept on the entity path for full parity)
    graphics.gltf(ch, "local/basegen8.glb")
    scene.set_pose("cam", { 0, 1.7, 0.4 }, { 0, 0, 0, 1 })
    scene.set("basegen8/Cornea.Material.refraction", 1.0)
    scene.set("basegen8/Cornea.Material.ior", 1.0)
    scene.set("basegen8/Cornea.Material.roughness", 0.0)
    scene.set("basegen8/EyeMoisture.Material.refraction", 1.0)
    scene.set("basegen8/EyeMoisture.Material.ior", 1.0)
    scene.set("basegen8/EyeMoisture.Material.roughness", 0.0)
    scene.set("basegen8/EyeMoisture.1.Material.refraction", 1.0)
    scene.set("basegen8/EyeMoisture.1.Material.ior", 1.0)
    scene.set("basegen8/EyeMoisture.1.Material.roughness", 0.0)
end
